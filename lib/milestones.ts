export function getCurrentMilestone(days: number) {
  return MILESTONES.filter((m) => m.days <= days).pop() || null;
}

export function getNextMilestone(days: number) {
  return MILESTONES.find((m) => m.days > days) || null;
}

export function getDaysToNextMilestone(days: number): number {
  const next = getNextMilestone(days);
  return next ? next.days - days : 0;
}

export function shouldShowPreMessage(days: number): boolean {
  const next = getNextMilestone(days);
  if (!next) return false;
  const diff = next.days - days;
  return diff <= 3 && diff > 0;
}
